"""Regenerate docs/results_tables.md from the CSVs in results/ (no number is typed by hand).
    python scripts/make_results_tables.py            (standard library only)"""
import csv
import glob
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"


def read(p):
    with open(p, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def md(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


L = ["# Result tables", "",
     "Generated by `scripts/make_results_tables.py` from the CSVs in `results/`. All numbers are on the "
     "held-out test set (192 sentences, one signer, seed 42) unless a table says otherwise. Pose "
     "errors are in shoulder-widths. **NAT + MSE** is the final system; the Progressive Transformer and "
     "the NAT + Diffusion + Velocity generator are the two alternatives it is compared with.", ""]

arch = read(RES / "main_comparison" / "architecture_comparison.csv")
bt = {r["condition"]: r for r in read(RES / "back_translation" / "summary.csv")}
bt_key = {"Progressive Transformer": "Progressive Transformer", "NAT + MSE": "NAT + MSE",
          "NAT + Diffusion + Velocity": "Diffusion (CFG 2.5)"}
L += ["## Architecture comparison", ""]
L.append(md(["Model", "DTW-MJE", "PCK@0.05", "PCK@0.1", "PCK@0.2", "PCK@0.5", "Motion ratio", "Length ratio",
             "Test time (192 videos)", "Back-translation WER (exploratory)"],
            [[r["model"], f"{float(r['dtw_mje']):.4f}", f"{float(r['pck_0.05']):.1f}", f"{float(r['pck_0.1']):.1f}",
              f"{float(r['pck_0.2']):.1f}", f"{float(r['pck_0.5']):.2f}", f"{float(r['motion_ratio']):.3f}",
              f"{float(r['length_ratio']):.3f}", f"{r['test_wall_seconds']} s ({r['inference_paradigm']})",
              f"{float(bt[bt_key[r['model']]]['wer_pct']):.1f}%"] for r in arch]))
L.append("")

L += ["## Back-translation", "",
      "A pose-to-gloss recogniser trained only on real training poses reads each model's output. The "
      "pre-registered validity gate (recogniser reads at least 90% of REAL test sentences exactly) was **not** "
      "met (81.8%), so this table is exploratory. CIs are 95% bootstrap over sentences.", ""]
L.append(md(["Condition", "Sentence exact %", "[95% CI]", "WER %", "[95% CI]", "BLEU-1", "BLEU-2"],
            [[r["condition"], f"{float(r['sentence_exact_pct']):.1f}",
              f"[{float(r['sentence_exact_ci_lo']):.1f}, {float(r['sentence_exact_ci_hi']):.1f}]",
              f"{float(r['wer_pct']):.1f}", f"[{float(r['wer_ci_lo']):.1f}, {float(r['wer_ci_hi']):.1f}]",
              f"{float(r['bleu1']):.1f}" if r["bleu1"] not in ("", "nan") else "-",
              f"{float(r['bleu2']):.1f}" if r["bleu2"] not in ("", "nan") else "-"] for r in bt.values()]))
L.append("")

L += ["## Cross-signer generalisation", "",
      "The same held-out sentences signed by four signers never seen in training (U5, U6, U7, U19; 768 videos). "
      "Each model generates as the training signer and is scored against the unseen signer's recording. "
      "The Progressive Transformer was not evaluated cross-signer. The NAT + MSE row is the weight-0 control run "
      "(same code and protocol as the main NAT + MSE model).", ""]
cs = read(RES / "main_comparison" / "cross_signer_per_video_diffusion.csv")
mean = lambda rows, k: sum(float(r[k]) for r in rows) / len(rows)
nat_cs = [r for r in read(RES / "nat_variance" / "nat_variance_w0.csv") if r["split"] == "cross_signer"][0]
L.append(md(["Model", "DTW-MJE", "PCK@0.5", "Motion ratio", "Length ratio", "Videos"],
            [["NAT + MSE (weight-0 control)", f"{float(nat_cs['dtw_mje']):.4f}", f"{float(nat_cs['pck_0.5']):.2f}",
              f"{float(nat_cs['motion_ratio']):.3f}", f"{float(nat_cs['length_ratio']):.3f}", nat_cs["n_videos"]],
             ["Diffusion (NAT+Diffusion+Velocity)", f"{mean(cs, 'dtw_mje'):.4f}", f"{mean(cs, 'PCK@0.5'):.2f}",
              f"{mean(cs, 'motion_ratio'):.3f}", f"{mean(cs, 'length_ratio'):.3f}", str(len(cs))]]))
L.append("")

L += ["## Velocity weight x guidance scale (diffusion generator)", ""]
grid = read(RES / "ablation" / "velocity_guidance_grid.csv")
L.append(md(["Velocity weight", "Guidance", "Epochs", "Motion ratio", "Jitter ratio", "DTW-MJE", "PCK@0.2", "PCK@0.5"],
            [[f"{float(r['velocity_weight']):g}", f"{float(r['cfg_scale']):g}",
              r["epochs_trained"] if r["epochs_trained"] != "0" else "452*", f"{float(r['motion_ratio']):.3f}",
              f"{float(r['jitter_ratio']):.2f}", f"{float(r['dtw_mje']):.3f}", f"{float(r['pck_0.2']):.1f}",
              f"{float(r['pck_0.5']):.1f}"] for r in grid]))
L += ["", "*The velocity-10 checkpoint is evaluated without retraining, so its epoch count is not logged here "
      "(it trained 452 epochs; see `results/training_histories/diffusion.csv`).", ""]

L += ["## Test-time smoothness guidance vs plain smoothing (diffusion checkpoint, guidance 2.5)", ""]
sm = read(RES / "ablation" / "smoothness_guidance_arms.csv")
L.append(md(["Arm", "Split", "DTW-MJE", "Motion ratio", "Jitter ratio", "PCK@0.5", "Sampling time"],
            [[r["arm"], r["split"], f"{float(r['dtw_mje']):.4f}", f"{float(r['motion_ratio']):.3f}",
              f"{float(r['jitter_ratio']):.3f}", f"{float(r['pck_0.5']):.2f}", f"{r['wall_seconds']} s"] for r in sm]))
L.append("")

L += ["## NAT + MSE with a temporal-variance penalty (weight 0 = plain MSE control)", ""]
nv_rows = []
for f in sorted(glob.glob(str(RES / "nat_variance" / "nat_variance_w*.csv")), key=lambda p: float(Path(p).stem.split("_w")[-1])):
    for r in read(f):
        nv_rows.append([f"{float(r['variance_weight']):g}", r["split"], r["epochs_trained"], f"{float(r['motion_ratio']):.3f}",
                        f"{float(r['jitter_ratio']):.3f}", f"{float(r['dtw_mje']):.4f}", f"{float(r['pck_0.5']):.2f}"])
L.append(md(["Weight", "Split", "Epochs", "Motion ratio", "Jitter ratio", "DTW-MJE", "PCK@0.5"], nv_rows))
L.append("")

out = ROOT / "docs" / "results_tables.md"
out.parent.mkdir(exist_ok=True)
out.write_text("\n".join(L), encoding="utf-8")
print("wrote", out.relative_to(ROOT))
